const lettersRoot = document.querySelector("#letters");
const tocItems = document.querySelector("#toc-items");

letters.forEach((letter, index) => {
  const number = String(index + 1).padStart(2, "0");
  const section = document.createElement("section");
  section.className = "page letter-page";
  section.id = `letter-${index + 1}`;
  section.innerHTML = `
    <p class="page-kicker">家书 ${number} / 09</p>
    <div class="letter-layout">
      <article class="letter-original">
        <div class="letter-heading"><span>${number}</span><div><small>FAMILY LETTER</small><h2>${letter.title}</h2></div></div>
        <p class="address">${letter.address}</p>
        ${letter.paragraphs.map(paragraph => `<p>${paragraph}</p>`).join("")}
        <p class="signature">${letter.sign}</p>
      </article>
      <aside class="annotations">
        <div class="annotation-heading"><span>注</span><div><small>ANNOTATIONS</small><h3>原书注释</h3></div></div>
        <ol>${letter.notes.map(([term, explanation]) => `<li><strong>${term}</strong><p>${explanation}</p></li>`).join("")}</ol>
      </aside>
    </div>`;
  lettersRoot.appendChild(section);

  const button = document.createElement("button");
  button.className = "toc-link";
  button.dataset.target = section.id;
  button.innerHTML = `<span>${number}</span>${letter.title.replace(/信$/, "")}`;
  tocItems.appendChild(button);
});

const book = document.querySelector("#book");
const pages = [...book.querySelectorAll(".page")];
const tocLinks = [...document.querySelectorAll(".toc-link")];
const currentPage = document.querySelector("#current-page");
const totalPages = document.querySelector("#total-pages");
const progressBar = document.querySelector("#progress-bar");
let mobileIndex = 0;
totalPages.textContent = String(pages.length).padStart(2, "0");

function isMobile() {
  return window.matchMedia("(max-width: 820px)").matches;
}

function activePageIndex() {
  if (isMobile()) return mobileIndex;
  const center = book.scrollLeft + book.clientWidth / 2;
  let bestIndex = 0;
  let bestDistance = Infinity;
  pages.forEach((page, index) => {
    const pageCenter = page.offsetLeft + page.offsetWidth / 2;
    const distance = Math.abs(center - pageCenter);
    if (distance < bestDistance) {
      bestDistance = distance;
      bestIndex = index;
    }
  });
  return bestIndex;
}

function updateNavigation() {
  const index = activePageIndex();
  pages.forEach((page, pageIndex) => page.classList.toggle("is-mobile-active", pageIndex === index));
  currentPage.textContent = String(index + 1).padStart(2, "0");
  progressBar.style.width = `${((index + 1) / pages.length) * 100}%`;
  tocLinks.forEach(link => link.classList.toggle("is-active", link.dataset.target === pages[index].id));
  document.querySelector("#prev-page").disabled = index === 0;
  document.querySelector("#next-page").disabled = index === pages.length - 1;
}

function goToPage(index) {
  const targetIndex = Math.max(0, Math.min(index, pages.length - 1));
  if (isMobile()) {
    mobileIndex = targetIndex;
    window.scrollTo({ top: 0, behavior: "smooth" });
    updateNavigation();
    return;
  }
  const next = pages[targetIndex];
  next.scrollIntoView({ behavior: "smooth", block: "nearest", inline: "start" });
}

tocLinks.forEach(link => link.addEventListener("click", () => {
  goToPage(pages.findIndex(page => page.id === link.dataset.target));
}));
document.querySelector("#prev-page").addEventListener("click", () => goToPage(activePageIndex() - 1));
document.querySelector("#next-page").addEventListener("click", () => goToPage(activePageIndex() + 1));
book.addEventListener("scroll", () => requestAnimationFrame(updateNavigation), { passive: true });
book.addEventListener("keydown", event => {
  if (event.key === "ArrowRight" || event.key === "PageDown") goToPage(activePageIndex() + 1);
  if (event.key === "ArrowLeft" || event.key === "PageUp") goToPage(activePageIndex() - 1);
});
window.addEventListener("resize", updateNavigation);
updateNavigation();
