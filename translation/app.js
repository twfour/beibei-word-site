const preferredFemaleVoiceNames = [
  "Samantha",
  "Ava",
  "Allison",
  "Susan",
  "Victoria",
  "Microsoft Aria",
  "Microsoft Jenny",
  "Microsoft Michelle",
  "Microsoft Zira",
  "Google US English",
  "Karen",
  "Moira",
  "Tessa",
  "Fiona"
];

function chooseFemaleEnglishVoice(voices) {
  const englishVoices = voices.filter(voice => /^en(?:-|_)/i.test(voice.lang));
  for (const preferredName of preferredFemaleVoiceNames) {
    const voice = englishVoices.find(candidate => candidate.name.includes(preferredName));
    if (voice) return voice;
  }
  return englishVoices.find(voice => /^en(?:-|_)US$/i.test(voice.lang))
    || englishVoices[0]
    || null;
}

function resetAudioButton() {
  if (!activeAudioButton) return;
  activeAudioButton.classList.remove("is-speaking");
  activeAudioButton.textContent = activeAudioButton.dataset.idleLabel || "▶ 朗读英文";
  activeAudioButton = null;
}

function stopSpeech() {
  if (activeAudioElement) {
    activeAudioElement.pause();
    activeAudioElement.currentTime = 0;
    activeAudioElement = null;
  }
  if ("speechSynthesis" in window) window.speechSynthesis.cancel();
  resetAudioButton();
}

function speakText(button, text, rate = 0.86) {
  if (!("speechSynthesis" in window) || !("SpeechSynthesisUtterance" in window)) return;
  if (activeAudioButton === button) {
    stopSpeech();
    return;
  }
  stopSpeech();
  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = "en-US";
  utterance.rate = rate;
  const voices = window.speechSynthesis.getVoices();
  utterance.voice = chooseFemaleEnglishVoice(voices);
  activeAudioButton = button;
  button.classList.add("is-speaking");
  button.textContent = button.dataset.speakingLabel || "■ 停止朗读";
  const finish = () => {
    if (activeAudioButton === button) resetAudioButton();
  };
  utterance.addEventListener("end", finish, { once: true });
  utterance.addEventListener("error", finish, { once: true });
  window.speechSynthesis.speak(utterance);
}

function playRecordedAudio(button, audioPath, fallbackText, fallbackRate = 0.86) {
  if (activeAudioButton === button) {
    stopSpeech();
    return;
  }
  stopSpeech();
  const audio = new Audio(audioPath);
  activeAudioElement = audio;
  activeAudioButton = button;
  button.classList.add("is-speaking");
  button.textContent = button.dataset.speakingLabel || "■ 停止朗读";
  const finish = () => {
    if (activeAudioElement !== audio) return;
    activeAudioElement = null;
    resetAudioButton();
  };
  const fallback = () => {
    if (activeAudioElement !== audio) return;
    activeAudioElement = null;
    resetAudioButton();
    speakText(button, fallbackText, fallbackRate);
  };
  audio.addEventListener("ended", finish, { once: true });
  audio.addEventListener("error", fallback, { once: true });
  audio.play().catch(fallback);
}

